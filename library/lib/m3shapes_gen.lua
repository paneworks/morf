-- Writes lib/m3shapes_paths.lua: every named shape's path data at the
-- library's defaults (a 100 square, shapes.SEGMENTS cubics), so a shell
-- that shows many shapes -- or morphs between them -- reads strings rather
-- than resampling outlines as it loads. Run it again after changing a shape:
--
--     cd examples && lua5.4 lib/m3shapes_gen.lua > lib/m3shapes_paths.lua
--
-- Plain Lua: `morf.ui` is stubbed, since only the geometry runs.

package.path = "./?.lua;" .. package.path
package.preload["morf.ui"] = function() return {} end
package.loaded["lib.m3shapes_paths"] = false
local shapes = require("lib.m3shapes")

local out = {
  "-- Generated by lib/m3shapes_gen.lua: each named shape's path data in a",
  "-- 100 square, " .. shapes.SEGMENTS .. " cubics. Do not edit.",
  "return {",
}
for _, name in ipairs(shapes.NAMES) do
  out[#out + 1] = ("  [%q] = %q,"):format(name, shapes.path(name, { fresh = true }))
end
out[#out + 1] = "}"
print(table.concat(out, "\n"))
