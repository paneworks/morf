#!/usr/bin/env python3
"""The installable morf skill, generated -- never hand-maintained.

    python3 tools/skill_gen.py           rewrite skill/SKILL.md
    python3 tools/skill_gen.py --check   fail when skill/SKILL.md is stale

Structure comes from `docs/UI.md` headings, the API inventory from the
same generated LuaLS definitions the docs gate reads
(`library/types/`, emitted by `morf types`), so the skill cannot drift
from the engine it describes. Hand-written prose lives only between
`<!-- hand-written: NAME -->` and `<!-- /hand-written -->` markers,
which regeneration preserves verbatim.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skill" / "SKILL.md"
HAND_WRITTEN = re.compile(
    r"<!-- hand-written: (\S+) -->\n(.*?)<!-- /hand-written -->", re.S)


def inventory():
    names = set()
    classes = {}
    current = None
    for line in (ROOT / "library" / "types" / "morf.lua").read_text().splitlines():
        if match := re.match(r"---@class (\S+)", line):
            current = match.group(1)
            classes.setdefault(current, [])
        elif (match := re.match(r"---@field (\S+)", line)) and current:
            classes[current].append(match.group(1))
    for class_name, fields in classes.items():
        if class_name.startswith("Morf"):
            base = ".".join(p[:1].lower() + p[1:] for p in class_name.split("."))
            for field in fields:
                names.add(f"{base}.{field}")
    ui_text = (ROOT / "library" / "types" / "morf" / "ui.lua").read_text()
    for constructor in re.findall(r"function (ui\.[A-Za-z]+)\(", ui_text):
        names.add(constructor)
        names.add(f"morf.{constructor}")
    return sorted(names)


def version():
    return re.search(
        r'\nversion\s*=\s*"([^"]+)"', (ROOT / "Cargo.toml").read_text()).group(1)


def guide_map():
    headings = []
    for line in (ROOT / "docs" / "UI.md").read_text().splitlines():
        if match := re.match(r"(#{1,3}) (.+)", line):
            headings.append(f"{'  ' * (len(match.group(1)) - 1)}- {match.group(2)}")
    return headings


def render(preserved=None):
    preserved = preserved or {}
    names = inventory()
    top = {}
    for name in names:
        top.setdefault(name.split(".")[1] if name.startswith("morf.") else "ui", []).append(name)
    lines = [
        "---",
        "name: morf",
        "description: Author morf shell configurations in Lua against this "
        "version's engine API.",
        "---",
        "",
        f"# morf {version()} -- shell authoring",
        "",
        "Generated by `tools/skill_gen.py` from `docs/UI.md` and the LuaLS",
        "definitions `morf types` emits; do not edit the generated sections.",
        "The full guide for this version: `morf docs --ui`. Its API",
        "reference: `morf docs`.",
        "",
        "## Guide map (docs/UI.md)",
        "",
        *guide_map(),
        "",
        "## API inventory (morf types)",
        "",
    ]
    for group in sorted(top):
        lines.append(f"### {group}")
        lines.append("")
        lines.append(", ".join(f"`{name}`" for name in top[group]))
        lines.append("")
    for name, body in preserved.items():
        lines.append(f"<!-- hand-written: {name} -->")
        lines.append(body.rstrip("\n"))
        lines.append("<!-- /hand-written -->")
        lines.append("")
    return "\n".join(lines)


def preserved_sections():
    if not SKILL.exists():
        return {}
    return {name: body for name, body in HAND_WRITTEN.findall(SKILL.read_text())}


def main():
    rendered = render(preserved_sections())
    if "--check" in sys.argv:
        if not SKILL.exists() or SKILL.read_text() != rendered:
            print("skill/SKILL.md is stale; run tools/skill_gen.py")
            return 1
        print("skill/SKILL.md is current")
        return 0
    SKILL.parent.mkdir(parents=True, exist_ok=True)
    SKILL.write_text(rendered)
    print(f"wrote {SKILL.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
